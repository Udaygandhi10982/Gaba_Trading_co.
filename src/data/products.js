export function getProductSlug(nameOrCode) {
  if (!nameOrCode) return '';
  return String(nameOrCode)
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function getProductBySlug(slug) {
  if (!slug) return null;
  return products.find(p => getProductSlug(p.name) === slug || p.id === slug || (p.code && p.code.toLowerCase() === slug.toLowerCase())) || null;
}

export function getProductById(id) {
  if (!id) return null;
  return products.find(p => p.id === id || p.code === id) || null;
}
